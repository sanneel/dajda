/**
 * Bake the bookmaker logo templates into a TypeScript module.
 *
 * The detector (src/lib/logo-detect.ts) matches uploaded slips against these
 * images. They are shipped as base64 inside a generated module rather than
 * read from disk at runtime, because a serverless bundle only reliably
 * carries what the code imports.
 *
 * Source images live in assets/bookmaker-logos/<brand>-<kind>.png. Each is
 * reduced to grayscale, trimmed of transparent margin, flattened onto the
 * ground that suits it (a white wordmark onto dark, everything else onto
 * white) and scaled to a fixed width, so the matcher's scale ladder starts
 * from a known size.
 *
 * Run after adding or replacing a logo:  node scripts/build-logo-templates.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import sharp from 'sharp';

const SOURCE_DIR = path.join(process.cwd(), 'assets', 'bookmaker-logos');
const OUT_FILE = path.join(process.cwd(), 'src', 'lib', 'bookmaker-logos.generated.ts');
const TEMPLATE_WIDTH = 160;

/** Human-readable brand names, keyed by the file name's brand prefix. */
const BRAND_NAMES = {
  adjarabet: 'Adjarabet',
  crocobet: 'Crocobet',
  europebet: 'Europebet',
  betlive: 'Betlive',
  leaderbet: 'Leaderbet',
  crystalbet: 'Crystalbet',
  mostbet: 'Mostbet',
  '1xbet': '1xBet',
  bet365: 'bet365',
  betsson: 'Betsson',
};

async function bake(file) {
  const [brandKey] = file.replace(/\.png$/, '').split('-');
  const name = BRAND_NAMES[brandKey] ?? brandKey;
  const source = sharp(path.join(SOURCE_DIR, file));
  // A logo drawn in white only exists against a dark ground; the rest sit
  // on white. Judged over the opaque pixels alone: transparent ones carry
  // whatever colour the exporter left behind, usually black.
  const { data, info } = await source
    .clone()
    .ensureAlpha()
    .raw()
    .toBuffer({ resolveWithObject: true });
  let sum = 0;
  let count = 0;
  for (let i = 0; i < data.length; i += info.channels) {
    if (data[i + 3] > 128) {
      sum += (data[i] + data[i + 1] + data[i + 2]) / 3;
      count += 1;
    }
  }
  const bright = count > 0 && sum / count > 200;
  const background = bright ? '#101010' : '#ffffff';

  const baked = await source
    .clone()
    .trim({ threshold: 10 })
    .flatten({ background })
    .resize({ width: TEMPLATE_WIDTH, kernel: 'lanczos3' })
    .grayscale()
    .raw()
    .toBuffer({ resolveWithObject: true });

  return {
    brand: name,
    file,
    width: baked.info.width,
    height: baked.info.height,
    gray: Buffer.from(baked.data).toString('base64'),
  };
}

const files = fs.readdirSync(SOURCE_DIR).filter((f) => f.endsWith('.png')).sort();
const templates = [];
for (const file of files) templates.push(await bake(file));

const lines = [
  '/* Generated by scripts/build-logo-templates.mjs from assets/bookmaker-logos. Do not edit. */',
  '',
  'export type LogoTemplate = {',
  '  brand: string;',
  '  file: string;',
  '  width: number;',
  '  height: number;',
  '  /** 8-bit grayscale pixels, row-major, base64. */',
  '  gray: string;',
  '};',
  '',
  'export const LOGO_TEMPLATES: LogoTemplate[] = [',
  ...templates.map(
    (t) =>
      `  { brand: ${JSON.stringify(t.brand)}, file: ${JSON.stringify(t.file)}, width: ${t.width}, height: ${t.height}, gray: ${JSON.stringify(t.gray)} },`,
  ),
  '];',
  '',
];
fs.writeFileSync(OUT_FILE, lines.join('\n'));
console.log(`wrote ${templates.length} templates to ${path.relative(process.cwd(), OUT_FILE)}`);
for (const t of templates) console.log(`  ${t.brand.padEnd(12)} ${t.file} ${t.width}x${t.height}`);
